struct ProviderIcon: View {
    let provider: UsageProvider
    var size: CGFloat = 20

    var body: some View {
        Group {
            if provider == .codex {
                OpenAIMark().fill(.primary)
            } else {
                Canvas { context, size in
                    var rays = Path()
                    let center = CGPoint(x: size.width / 2, y: size.height / 2)
                    let radius = min(size.width, size.height) * 0.45
                    for index in 0..<16 {
                        let angle = Double(index) * .pi / 8
                        rays.move(to: center)
                        rays.addLine(to: CGPoint(x: center.x + cos(angle) * radius,
                                                 y: center.y + sin(angle) * radius))
                    }
                    context.stroke(rays, with: .color(Color(red: 0.77, green: 0.45, blue: 0.32)),
                                   style: StrokeStyle(lineWidth: max(1.3, size.width * 0.065), lineCap: .round))
                }
            }
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }
}
